import { readFile, readdir, stat, writeFile, mkdir } from "node:fs/promises";
import { relative, resolve, dirname, extname, join } from "node:path";

const root = process.cwd();
const sourceRoots = ["apps/web/src", "apps/server/src"];
const outputJson = resolve(root, "docs/architecture/persistence-audit.json");
const outputMarkdown = resolve(root, "docs/architecture/persistence-audit-phase-1.md");
const writeOutputs = process.argv.includes("--write");
const checkOnly = process.argv.includes("--check");
const supportedExtensions = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);

const patterns = {
  localStorage: /\b(?:window\.)?localStorage\b/g,
  indexedDB: /\bindexedDB\b/g,
  fetch: /\bfetch\s*\(/g,
  sharedApi: /\/api\/shared-budget\//g,
  sqlite: /\b(?:SQLite|sqlite|better-sqlite3|drizzle-orm)\b/g,
  persistenceGateway: /\b(?:PersistenceGateway|PersistenceProvider|PersistencePort|KeyValueStoragePort)\b/g,
};

const uiPreferenceHints = [
  "/stores/uiStore.",
  "/tableLayout/",
  "/registerSorting.",
];

function classifyLocalStorage(path) {
  return uiPreferenceHints.some(hint => path.includes(hint))
    ? "ui-preference"
    : "budget-or-runtime-data";
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (["node_modules", "dist", "build", ".git"].includes(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (supportedExtensions.has(extname(entry.name))) files.push(path);
  }
  return files;
}

function lineNumberAt(text, offset) {
  return text.slice(0, offset).split("\n").length;
}

async function scan() {
  const files = (await Promise.all(sourceRoots.map(path => walk(resolve(root, path))))).flat();
  const findings = [];
  const filesByPattern = Object.fromEntries(Object.keys(patterns).map(key => [key, new Set()]));

  for (const absolutePath of files) {
    const path = relative(root, absolutePath).replaceAll("\\", "/");
    const text = await readFile(absolutePath, "utf8");
    for (const [kind, expression] of Object.entries(patterns)) {
      expression.lastIndex = 0;
      for (const match of text.matchAll(expression)) {
        filesByPattern[kind].add(path);
        findings.push({
          kind,
          path,
          line: lineNumberAt(text, match.index ?? 0),
          classification: kind === "localStorage" ? classifyLocalStorage(path) : undefined,
        });
      }
    }
  }

  const localStorageFiles = [...filesByPattern.localStorage].sort();
  const directBudgetStorageFiles = localStorageFiles.filter(path => classifyLocalStorage(path) === "budget-or-runtime-data");
  const uiPreferenceStorageFiles = localStorageFiles.filter(path => classifyLocalStorage(path) === "ui-preference");

  return {
    generatedAt: new Date().toISOString(),
    scope: sourceRoots,
    architecture: {
      browserDefault: "browser-local-storage",
      configurableBrowserBackends: ["browser-local-storage", "shared-server"],
      sqliteStatus: "adapter foundation exists but is not selectable through browser runtime configuration",
      sharedServerModel: "server-authoritative key/value snapshot with optimistic whole-revision concurrency and SSE invalidation",
      attachmentContent: "separate IndexedDB blob store foundation",
    },
    counts: Object.fromEntries(Object.entries(filesByPattern).map(([key, value]) => [key, value.size])),
    localStorage: {
      directBudgetOrRuntimeDataFiles: directBudgetStorageFiles,
      uiPreferenceFiles: uiPreferenceStorageFiles,
    },
    persistenceFiles: [...filesByPattern.persistenceGateway].sort(),
    sqliteFiles: [...filesByPattern.sqlite].sort(),
    sharedApiFiles: [...filesByPattern.sharedApi].sort(),
    findings,
  };
}

function markdown(report) {
  const list = values => values.length ? values.map(value => `- \`${value}\``).join("\n") : "- None detected";
  return `# Phase 1 Persistence Audit\n\n` +
`Generated by \`pnpm audit:persistence\`. The JSON companion is intended for automated comparison in later phases. The migration roadmap and decisions live in [\`local-first-migration.md\`](./local-first-migration.md).\n\n` +
`## Executive summary\n\n` +
`Budget App has a useful persistence boundary, but the browser runtime is not local-first yet. The default provider is browser local storage, while shared-server mode replaces that provider with a server-authoritative key/value store. SQLite account, payee, and register adapters exist as validated foundations, but browser runtime configuration cannot select them.\n\n` +
`The Shared Platform server stores string values in SQLite, protects the complete key/value namespace with one revision, broadcasts revision invalidations over SSE, and requires clients to reload the authoritative snapshot after remote changes. This is the principal architecture to replace during Phases 2–5.\n\n` +
`## Current runtime topology\n\n` +
`\`\`\`text\nReact UI\n  ↓\nBudgetPersistenceProvider / AppPersistenceGateway\n  ├─ browser-local-storage (default)\n  └─ shared-server (deployment option)\n       ↓ HTTP key/value operations\nShared Platform server\n       ↓\nshared-budget.sqlite\n\`\`\`\n\n` +
`SQLite domain adapters exist beside this path, but they are not the authoritative browser runtime.\n\n` +
`## Automated inventory\n\n` +
`| Signal | Files |\n|---|---:|\n` +
Object.entries(report.counts).map(([key, value]) => `| ${key} | ${value} |`).join("\n") +
`\n\n### Direct browser-storage dependencies requiring migration review\n\n${list(report.localStorage.directBudgetOrRuntimeDataFiles)}\n\n` +
`### Browser-storage uses that are UI preferences, not budget authority\n\n${list(report.localStorage.uiPreferenceFiles)}\n\n` +
`### Shared Platform API consumers and server routes\n\n${list(report.sharedApiFiles)}\n\n` +
`### SQLite-related implementation files\n\n${list(report.sqliteFiles)}\n\n` +
`## Read and write paths\n\n` +
`### Browser-local mode\n\n` +
`Feature services use the active persistence gateway and generic key/value storage, but several features still access \`window.localStorage\` directly. Large values can spill into IndexedDB through the key/value port. The browser copy is authoritative only on that browser.\n\n` +
`### Shared-server mode\n\n` +
`The client sends key-level set/remove batches with an expected global revision. The server commits them to \`shared_storage\`, increments one revision, and announces it through SSE. A revision conflict rejects the complete batch. Remote invalidation causes the client to obtain a current snapshot rather than replaying domain operations.\n\n` +
`### SQLite adapter foundation\n\n` +
`SQLite adapters already exist for accounts, payees, and substantial register behaviour. They provide the main seam for Phase 2, but unsupported mutations and schema gaps must be resolved before SQLite can become authoritative.\n\n` +
`### Attachments\n\n` +
`Attachment metadata remains part of register persistence. New attachment content is separated behind an attachment content-store boundary and stored in IndexedDB in the browser. Remote blob transfer, manifests, lifecycle cleanup, and checkpoint integration are not implemented yet.\n\n` +
`## Migration constraints\n\n` +
`1. No UI feature should need to know whether data is local or synchronised.\n` +
`2. SQLite must become the local source of truth before incremental sync is introduced.\n` +
`3. Shared-server mode cannot remain a second authoritative implementation; it must become a sync transport.\n` +
`4. Direct budget-data localStorage access must move behind repositories or explicit preference stores.\n` +
`5. Attachments require metadata operations plus separate immutable blob transfer.\n` +
`6. Existing browser and shared-server budgets need a recoverable migration path and export checkpoint.\n\n` +
`## Phase 2 entry criteria\n\n` +
`- Choose the browser SQLite runtime (OPFS-backed SQLite or a host-provided SQLite gateway).\n` +
`- Complete the SQLite schema gap list for all active feature ports.\n` +
`- Define one authoritative transaction boundary for local writes.\n` +
`- Classify every direct localStorage use as budget data, migration compatibility, or UI preference.\n` +
`- Add parity tests that execute the same repository contract against the current and SQLite providers.\n` +
`- Preserve a one-click export before activating SQLite authority.\n\n` +
`## How to refresh this audit\n\n` +
`Run:\n\n\`\`\`bash\npnpm audit:persistence\n\`\`\`\n\n` +
`Use \`pnpm audit:persistence:check\` in CI to fail when the committed report is stale.\n`;
}

const report = await scan();
const renderedMarkdown = markdown(report);
const renderedJson = JSON.stringify(report, null, 2) + "\n";

if (checkOnly) {
  let existingMarkdown = "";
  let existingJson = "";
  try {
    existingMarkdown = await readFile(outputMarkdown, "utf8");
    existingJson = await readFile(outputJson, "utf8");
  } catch {
    console.error("Persistence audit outputs are missing. Run pnpm audit:persistence.");
    process.exit(1);
  }

  // generatedAt is intentionally ignored for JSON freshness checks.
  const existingReport = JSON.parse(existingJson);
  delete existingReport.generatedAt;
  const currentComparable = structuredClone(report);
  delete currentComparable.generatedAt;
  const markdownComparable = renderedMarkdown.replace(/^Generated by .*$/m, existingMarkdown.match(/^Generated by .*$/m)?.[0] ?? "");
  if (JSON.stringify(existingReport) !== JSON.stringify(currentComparable) || existingMarkdown !== markdownComparable) {
    console.error("Persistence audit outputs are stale. Run pnpm audit:persistence and commit the changes.");
    process.exit(1);
  }
  console.log("Persistence audit is current.");
  process.exit(0);
}

if (writeOutputs || !checkOnly) {
  await mkdir(dirname(outputJson), { recursive: true });
  await writeFile(outputJson, renderedJson);
  await writeFile(outputMarkdown, renderedMarkdown);
}

console.log("Persistence audit complete.");
console.log(`  direct budget/runtime localStorage files: ${report.localStorage.directBudgetOrRuntimeDataFiles.length}`);
console.log(`  UI-preference localStorage files: ${report.localStorage.uiPreferenceFiles.length}`);
console.log(`  SQLite-related files: ${report.sqliteFiles.length}`);
console.log(`  Shared Platform API files: ${report.sharedApiFiles.length}`);
console.log(`  report: ${relative(root, outputMarkdown)}`);
