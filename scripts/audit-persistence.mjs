import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, resolve } from "node:path";

const root = process.cwd();
const sourceRoots = ["apps/web/src", "apps/server/src"];
const outputJson = resolve(root, "docs/architecture/persistence-audit.json");
const outputMarkdown = resolve(root, "docs/architecture/persistence-audit-phase-1.md");
const checkOnly = process.argv.includes("--check");
const supportedExtensions = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);

const patterns = {
  localStorage: /\b(?:window\.)?localStorage\b/g,
  indexedDB: /\bindexedDB\b/g,
  replicationApi: /\/api\/replication\//g,
  persistenceBoundary: /\b(?:BudgetPersistenceProvider|PersistencePort|KeyValueStoragePort)\b/g,
  operationJournal: /\bOperationJournal(?:Port|Entry|Cursor)?\b/g,
  checkpoints: /\b(?:PersistenceCheckpoint|CheckpointPort)\b/g,
};

const uiPreferenceHints = [
  "/stores/uiStore.",
  "/tableLayout/",
  "/registerSorting.",
  "/features/settings/",
];

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (["node_modules", "dist", "build", ".git"].includes(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (supportedExtensions.has(extname(entry.name))) files.push(path);
  }
  return files;
}

function lineNumberAt(text, offset) {
  return text.slice(0, offset).split("\n").length;
}

function classifyLocalStorage(path) {
  if (path.endsWith("keyValueStoragePort.ts")) {
    return "legacy-or-test-browser-storage";
  }
  return uiPreferenceHints.some(hint => path.includes(hint))
    ? "ui-preference"
    : "review-required";
}

async function scan() {
  const files = (await Promise.all(sourceRoots.map(path => walk(resolve(root, path))))).flat();
  const findings = [];
  const filesByPattern = Object.fromEntries(Object.keys(patterns).map(key => [key, new Set()]));

  for (const absolutePath of files) {
    const path = relative(root, absolutePath).replaceAll("\\", "/");
    const text = await readFile(absolutePath, "utf8");
    for (const [kind, expression] of Object.entries(patterns)) {
      expression.lastIndex = 0;
      for (const match of text.matchAll(expression)) {
        filesByPattern[kind].add(path);
        findings.push({
          kind,
          path,
          line: lineNumberAt(text, match.index ?? 0),
          classification: kind === "localStorage" ? classifyLocalStorage(path) : undefined,
        });
      }
    }
  }

  const localStorageFiles = [...filesByPattern.localStorage].sort();
  return {
    generatedAt: new Date().toISOString(),
    scope: sourceRoots,
    architecture: {
      browserRuntime: "local-database",
      legacyBrowserStorage: "one-way snapshot migration plus intentionally global browser preferences",
      serverModel: "checkpoint, operation, blob, and cursor replication service",
      localAuthority: "IndexedDB-backed local database provider",
      reactiveUpdates: "persistence change bus publishes batched remote changes to React consumers",
    },
    counts: Object.fromEntries(Object.entries(filesByPattern).map(([key, value]) => [key, value.size])),
    localStorage: {
      migrationOrGlobalStorageFiles: localStorageFiles.filter(path => classifyLocalStorage(path) === "legacy-migration-or-global-browser-storage"),
      uiPreferenceFiles: localStorageFiles.filter(path => classifyLocalStorage(path) === "ui-preference"),
      reviewRequiredFiles: localStorageFiles.filter(path => classifyLocalStorage(path) === "review-required"),
    },
    persistenceBoundaryFiles: [...filesByPattern.persistenceBoundary].sort(),
    replicationApiFiles: [...filesByPattern.replicationApi].sort(),
    findings,
  };
}

function list(values) {
  return values.length ? values.map(value => `- \`${value}\``).join("\n") : "- None detected";
}

function markdown(report) {
  return `# Persistence Architecture Audit\n\n` +
`Generated by \`pnpm audit:persistence\`. The JSON companion supports automated freshness checks.\n\n` +
`## Current topology\n\n` +
`\`\`\`text\nReact features\n  ↓\nBudgetPersistenceProvider\n  ↓\nLocal database (authoritative)\n  ├─ operation journal\n  ├─ checkpoints\n  ├─ conflicts\n  └─ attachment content\n       ↓\nReplication engine\n       ↓\nReplication server\n\`\`\`\n\n` +
`The browser-local-storage provider and shared-server runtime have been removed. Legacy browser budget data is available only through a one-way canonical snapshot reader during first-run migration.\n\n` +
`## Automated inventory\n\n| Signal | Files |\n|---|---:|\n` +
Object.entries(report.counts).map(([key, value]) => `| ${key} | ${value} |`).join("\n") +
`\n\n### Legacy migration or global browser storage\n\n${list(report.localStorage.migrationOrGlobalStorageFiles)}\n\n` +
`### UI preference storage\n\n${list(report.localStorage.uiPreferenceFiles)}\n\n` +
`### Direct localStorage references requiring review\n\n${list(report.localStorage.reviewRequiredFiles)}\n\n` +
`### Replication API implementation and consumers\n\n${list(report.replicationApiFiles)}\n\n` +
`## Architecture rules\n\n` +
`1. The local database is the sole browser budget persistence runtime.\n` +
`2. Loading feature code before a provider is configured is an error; there is no implicit fallback.\n` +
`3. Legacy localStorage budget data may only cross the migration snapshot boundary.\n` +
`4. Remote operations update local authority first, then publish a batched reactive change.\n` +
`5. Attachment bytes travel through the independent hash-addressed blob channel.\n\n` +
`## Refreshing the audit\n\nRun \`pnpm audit:persistence\`; CI can use \`pnpm audit:persistence:check\`.\n`;
}

const report = await scan();
const renderedMarkdown = markdown(report);
const renderedJson = JSON.stringify(report, null, 2) + "\n";

if (checkOnly) {
  try {
    const existingMarkdown = await readFile(outputMarkdown, "utf8");
    const existingReport = JSON.parse(await readFile(outputJson, "utf8"));
    delete existingReport.generatedAt;
    const currentComparable = structuredClone(report);
    delete currentComparable.generatedAt;
    if (existingMarkdown !== renderedMarkdown || JSON.stringify(existingReport) !== JSON.stringify(currentComparable)) {
      console.error("Persistence audit outputs are stale. Run pnpm audit:persistence and commit the changes.");
      process.exit(1);
    }
  } catch {
    console.error("Persistence audit outputs are missing. Run pnpm audit:persistence.");
    process.exit(1);
  }
  console.log("Persistence audit is current.");
  process.exit(0);
}

await mkdir(dirname(outputJson), { recursive: true });
await writeFile(outputJson, renderedJson);
await writeFile(outputMarkdown, renderedMarkdown);
console.log("Persistence audit complete.");
console.log(`  report: ${relative(root, outputMarkdown)}`);
