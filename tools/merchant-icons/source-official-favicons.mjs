function iconLinks(html, base) {
  const tags = [...html.matchAll(/<link\b[^>]*>/giu)].map(([tag]) => tag);
  const links = tags.flatMap((tag) => {
    const rel = /\brel=["']([^"']+)["']/iu.exec(tag)?.[1] ?? "";
    const href = /\bhref=["']([^"']+)["']/iu.exec(tag)?.[1];
    if (!href || !/(?:apple-touch-icon|icon)/iu.test(rel)) return [];
    try { return [new URL(href, base).href]; } catch { return []; }
  });
  return [...links.reverse(), new URL("/favicon.ico", base).href];
}

async function sourceOfficialIcon(key, source) {
  try {
    const page = await fetch(source, { redirect: "follow", signal: AbortSignal.timeout(10_000) });
    const candidates = iconLinks(await page.text(), page.url);
    let saved;
    for (const url of candidates) {
      try {
        const response = await fetch(url, { redirect: "follow", signal: AbortSignal.timeout(8_000) });
        const type = (response.headers.get("content-type") ?? "").split(";")[0];
        if (!response.ok || !type.startsWith("image/")) continue;
        const bytes = new Uint8Array(await response.arrayBuffer());
        if (bytes.length < 100 || bytes.length > 500_000) continue;
        const extension = type.includes("svg") ? "svg" : type.includes("png") ? "png" : type.includes("webp") ? "webp" : type.includes("jpeg") ? "jpg" : "ico";
        const file = `${key}.${extension}`;
        await writeFile(resolve(outputDir, file), bytes);
        saved = { key, assetPath: `official/${file}`, source, assetSource: response.url };
        break;
      } catch { /* try the next official icon declaration */ }
    }
    if (!saved) console.warn(`No usable official icon: ${key} (${source})`);
    return saved;
  } catch (error) {
    console.warn(`Official site unavailable: ${key} (${source}): ${error instanceof Error ? error.message : error}`);
    return undefined;
  }
}

